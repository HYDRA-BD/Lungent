def map_fields(schema_path=SCHEMA_FILE):
    if not os.path.exists(schema_path):
        print(f"[!] Error: Schema file not found: {schema_path}")
        print("    Please run `python scrape_form.py` first to generate form_schema.json.")
        return

    with open(schema_path, "r", encoding="utf-8") as f:
        schema = json.load(f)

    fill_plan = {
        "text_inputs": [],
        "textareas": [],
        "checkboxes": [],
        "selects": []
    }

    # 1. Match standard text inputs
    for inp in schema.get("inputs", []):
        combined_text = f"{inp.get('label', '')} {inp.get('placeholder', '')} {inp.get('name', '')} {inp.get('id', '')}".lower()
        matched_val = None
        for pattern, val in FIELD_RULES:
            if re.search(pattern, combined_text):
                matched_val = val
                break
        
        if matched_val:
            fill_plan["text_inputs"].append({
                "selector": inp["selector"],
                "label": inp.get("label", ""),
                "value": matched_val
            })

    # 2. Match textareas
    for ta in schema.get("textareas", []):
        combined_text = f"{ta.get('label', '')} {ta.get('placeholder', '')} {ta.get('name', '')} {ta.get('id', '')}".lower()
        matched_val = None
        for pattern, val in FIELD_RULES:
            if re.search(pattern, combined_text):
                matched_val = val
                break
        
        # If no specific rule matched but it's an overview/summary textarea
        if not matched_val:
            if "problem" in combined_text:
                matched_val = LUNGENT_KNOWLEDGE["problem_statement"]
            elif "solution" in combined_text:
                matched_val = LUNGENT_KNOWLEDGE["solution_description"]
            elif "summary" in combined_text or "description" in combined_text:
                matched_val = LUNGENT_KNOWLEDGE["public_summary"]

        if matched_val:
            fill_plan["textareas"].append({
                "selector": ta["selector"],
                "label": ta.get("label", ""),
                "value": matched_val
            })

    # 3. Match checkboxes
    for cb in schema.get("checkboxes", []):
        combined_text = f"{cb.get('label', '')} {cb.get('name', '')} {cb.get('id', '')}".lower()
        should_check = False
        for kw in CHECKBOX_POSITIVE_KEYWORDS:
            if kw in combined_text:
                should_check = True
                break
        
        if should_check:
            fill_plan["checkboxes"].append({
                "selector": cb["selector"],
                "label": cb.get("label", ""),
                "action": "check"
            })

    # 4. Match selects / dropdowns
    for sel in schema.get("selects", []):
        label_text = sel.get("label", "").lower()
        options = sel.get("options", [])
        chosen_val = None

        if "track" in label_text or "category" in label_text or "domain" in label_text:
            for opt in options:
                opt_lower = opt["text"].lower()
                if "healthcare" in opt_lower or "life science" in opt_lower or "unicorn" in opt_lower or "idea" in opt_lower:
                    chosen_val = opt["value"] or opt["text"]
                    break

        if chosen_val:
            fill_plan["selects"].append({
                "selector": sel["selector"],
                "label": sel.get("label", ""),
                "value": chosen_val
            })

    # Save mapping file
    with open(OUTPUT_MAPPED_FILE, "w", encoding="utf-8") as f:
        json.dump(fill_plan, f, indent=2, ensure_ascii=False)

    print("\n========================================================")
    print("  Lungent Form Mapper Complete")
    print("========================================================")
    print(f"[+] Mapped Text Inputs:  {len(fill_plan['text_inputs'])}")
    print(f"[+] Mapped Textareas:    {len(fill_plan['textareas'])}")
    print(f"[+] Mapped Checkboxes:   {len(fill_plan['checkboxes'])}")
    print(f"[+] Mapped Selects:      {len(fill_plan['selects'])}")
    print(f"[✓] Output written to:   {OUTPUT_MAPPED_FILE}\n")

if __name__ == "__main__":
    map_fields()
