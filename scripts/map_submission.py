def map_fields(schema_path=SCHEMA_FILE):
    if not os.path.exists(schema_path):
        print(f"[!] Error: Schema file not found: {schema_path}")
        print("    Please run `python scrape_form.py` first.")
        return

    with open(schema_path, "r", encoding="utf-8") as f:
        schema = json.load(f)

    fill_plan = {
        "text_inputs": [],
        "textareas": [],
        "checkboxes": [],
        "selects": []
    }

    # 1. Text Inputs
    for inp in schema.get("inputs", []):
        combined = f"{inp.get('tab', '')} {inp.get('label', '')} {inp.get('placeholder', '')} {inp.get('name', '')} {inp.get('id', '')}".lower()
        matched_val = None
        for pattern, val in FIELD_RULES:
            if re.search(pattern, combined):
                matched_val = val
                break
        
        if matched_val:
            fill_plan["text_inputs"].append({
                "tab": inp.get("tab", ""),
                "selector": inp["selector"],
                "label": inp.get("label", ""),
                "placeholder": inp.get("placeholder", ""),
                "value": matched_val
            })

    # 2. Textareas
    for ta in schema.get("textareas", []):
        combined = f"{ta.get('tab', '')} {ta.get('label', '')} {ta.get('placeholder', '')} {ta.get('name', '')} {ta.get('id', '')}".lower()
        matched_val = None
        for pattern, val in FIELD_RULES:
            if re.search(pattern, combined):
                matched_val = val
                break
        
        if not matched_val:
            if "data source" in combined:
                matched_val = LUNGENT_KNOWLEDGE["data_sources"]
            elif "model" in combined:
                matched_val = LUNGENT_KNOWLEDGE["ai_models"]
            elif "responsible" in combined:
                matched_val = LUNGENT_KNOWLEDGE["responsible_ai"]
            elif "rule" in combined:
                matched_val = LUNGENT_KNOWLEDGE["cursorrules_content"]
            elif "prompt" in combined:
                matched_val = LUNGENT_KNOWLEDGE["prompt_content"]

        if matched_val:
            fill_plan["textareas"].append({
                "tab": ta.get("tab", ""),
                "selector": ta["selector"],
                "label": ta.get("label", ""),
                "placeholder": ta.get("placeholder", ""),
                "value": matched_val
            })

    # 3. Checkboxes (both native and ARIA)
    for cb in schema.get("checkboxes", []):
        combined = f"{cb.get('tab', '')} {cb.get('label', '')} {cb.get('name', '')} {cb.get('id', '')}".lower()
        should_check = False
        for kw in CHECKBOX_POSITIVE_KEYWORDS:
            if kw in combined:
                should_check = True
                break
        
        if should_check:
            fill_plan["checkboxes"].append({
                "tab": cb.get("tab", ""),
                "selector": cb["selector"],
                "label": cb.get("label", ""),
                "ariaRole": cb.get("ariaRole", "checkbox"),
                "action": "check"
            })

    # 4. Selects / Dropdowns
    for sel in schema.get("selects", []):
        label_text = sel.get("label", "").lower()
        options = sel.get("options", [])
        chosen_val = None

        if "track" in label_text or "category" in label_text or "domain" in label_text:
            for opt in options:
                opt_lower = opt["text"].lower()
                if "healthcare" in opt_lower or "life science" in opt_lower or "unicorn" in opt_lower or "idea" in opt_lower:
                    chosen_val = opt["value"] or opt["text"]
                    break

        if chosen_val:
            fill_plan["selects"].append({
                "tab": sel.get("tab", ""),
                "selector": sel["selector"],
                "label": sel.get("label", ""),
                "value": chosen_val
            })

    with open(OUTPUT_MAPPED_FILE, "w", encoding="utf-8") as f:
        json.dump(fill_plan, f, indent=2, ensure_ascii=False)

    print("\n========================================================")
    print("  ✓ LUNGENT MULTI-TAB MAPPER COMPLETE")
    print("========================================================")
    print(f"Mapped Text Inputs:  {len(fill_plan['text_inputs'])}")
    print(f"Mapped Textareas:    {len(fill_plan['textareas'])}")
    print(f"Mapped Checkboxes:   {len(fill_plan['checkboxes'])}")
    print(f"Mapped Selects:      {len(fill_plan['selects'])}")
    print(f"\n[✓] Mapped data written to: {OUTPUT_MAPPED_FILE}\n")

if __name__ == "__main__":
    map_fields()
